#!/usr/bin/env python3
"""Embed an unchanged native engine library for the default package consumer."""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import tempfile
import PackageLibrary


def bundle(source, package, target):
    source, package = Path(source).resolve(), Path(package).resolve()
    # The existing simulator build is qualified on this target only.
    if target != "macos-arm64":
        raise ValueError("Only the existing macos-arm64 renderer is qualified")
    header = (source / "RenderReference").read_bytes()[:8]
    if len(header) != 8 or struct.unpack("<II", header) != (0xFEEDFACF, 0x0100000C):
        raise ValueError("Renderer is not a macOS ARM64 executable")
    if (source / "EngineLibrary.txt").read_text() != "silex-engine-library-v3\n":
        raise ValueError("A v3 library is required")
    asset = package / "Assets/Engines" / target
    module = package / "Target" / target / "Module/Engines/DefaultAssets.sx"
    asset.mkdir(parents=True, exist_ok=True)
    module.parent.mkdir(parents=True, exist_ok=True)
    packed = bytearray()
    entries = []
    with tempfile.TemporaryDirectory(prefix="silex-engine-bundle-") as temporary:
        staged = Path(temporary) / "library"
        PackageLibrary.stage(source, staged)
        for path in sorted(staged.rglob("*")):
            if not path.is_file():
                continue
            name = path.relative_to(staged).as_posix()
            data = path.read_bytes()
            start = len(packed)
            packed.extend(data)
            entries.append(dict(path=name, offset=start, size=len(data), sha256=hashlib.sha256(data).hexdigest()))
    (asset / "Library.bin").write_bytes(packed)
    manifest = dict(schema=1, target=target, sha256=hashlib.sha256(packed).hexdigest(), files=entries)
    (asset / "Manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    code = ['// Generated by Native/EngineSimulator/BundleLibrary.py; preserves every deployed byte.',
            'use STD.Error', 'use GFX.Audio.Engines.EngineFiles', '',
            'func populate(files:&EngineFiles) Result<void, Error> {',
            '    let bytes = embed_bytes("../../../../Assets/Engines/' + target + '/Library.bin")']
    for entry in entries:
        code.append('    try files.write(' + json.dumps(entry['path']) + ', @bytes[' +
                    str(entry['offset']) + ':' + str(entry['offset'] + entry['size']) +
                    ']) else error { return Result<void,Error>.failure(error) }')
    code += ['    return Result<void,Error>.success()', '}', '']
    module.write_text("\n".join(code))
    print("Embedded", len(entries), "files,", len(packed), "bytes; SHA-256", manifest['sha256'])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--from-build", required=True, type=Path)
    parser.add_argument("--package", type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument("--target", default="macos-arm64")
    args = parser.parse_args()
    bundle(args.from_build, args.package, args.target)
